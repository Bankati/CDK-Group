/** Réservations fictives réalistes pour le MODE DÉMO. */
export function seedBookings(now = Date.now()): Booking[] {
  return rows.map(({ createdDaysAgo, ...r }, i) => {
    const pkg = getPackage(r.packageId)!;
    const created =
      createdDaysAgo === 0 ? now - (8 + i) * 60_000 : now - createdDaysAgo * 86_400_000;
    return {
      ...r,
      id: `demo-${i + 1}`,
      code: `OCD-D${String(i + 1).padStart(3, "0")}`,
      createdAt: new Date(created).toISOString(),
      durationMinutes: pkg.durationMinutes,
      amount: pkg.price,
      // Les réservations « en attente » de la démo restent bloquées le temps prévu (config).
      holdExpiresAt: new Date(created + booking.holdHours * 3_600_000).toISOString(),
      validatedAt:
        r.status === "confirmed" ? new Date(created + 3_600_000).toISOString() : undefined,
    };
  });
}
